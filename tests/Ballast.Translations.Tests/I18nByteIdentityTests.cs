namespace Ballast.Translations.Tests;

/// <summary>
/// The generator against the output of the build script it replaces. The inputs are copies of a real site's .resx files and error-code
/// map, and the expected files are what the Node script wrote for those copies, byte for byte. The script's own header is passed, so the
/// first line matches too.
/// </summary>
public class I18nByteIdentityTests
{
    // The first line of the script's output: the header the replaced build script wrote.
    private const string ScriptHeader = "// Generated by build/generate-i18n.mjs — do not edit manually";

    [Fact]
    public void The_generator_writes_the_same_bytes_as_the_script_it_replaces()
    {
        using var folder = TempFolder.Create();
        var webRoot = Path.Combine(folder.Path, "wwwroot");

        var result = I18nGenerator.Generate(new I18nGeneratorOptions
        {
            SourceDirectory = TestData.Fixture("i18n"),
            OutputDirectory = Path.Combine(webRoot, "i18n"),
            DataFile = Path.Combine(webRoot, "js", "i18n-data.js"),
            ErrorCodesFile = TestData.Fixture("i18n/api-error-codes.json"),
            Header = ScriptHeader,
        });

        Assert.Equal("en,hr", string.Join(",", result.Cultures));
        Assert.Equal("1866,1866", string.Join(",", result.Keys));
        Assert.Equal(24, result.StatusKeys);
        Assert.Empty(result.Warnings);

        AssertSameBytes(TestData.Fixture("i18n/expected/i18n/en.json"), Path.Combine(webRoot, "i18n", "en.json"));
        AssertSameBytes(TestData.Fixture("i18n/expected/i18n/hr.json"), Path.Combine(webRoot, "i18n", "hr.json"));
        AssertSameBytes(TestData.Fixture("i18n/expected/js/i18n-data.js"), Path.Combine(webRoot, "js", "i18n-data.js"));
    }

    private static void AssertSameBytes(string expectedPath, string actualPath)
    {
        var expected = File.ReadAllBytes(expectedPath);
        var actual = File.ReadAllBytes(actualPath);
        var at = FirstDifference(expected, actual);
        Assert.True(at < 0,
            $"{Path.GetFileName(actualPath)} differs from the script's output at byte {at} (lengths {expected.Length} and {actual.Length}).");
    }

    // The index of the first byte that differs, or -1 when the two are the same.
    private static int FirstDifference(byte[] expected, byte[] actual)
    {
        var shared = Math.Min(expected.Length, actual.Length);
        for (var i = 0; i < shared; i++)
        {
            if (expected[i] != actual[i])
            {
                return i;
            }
        }

        return expected.Length == actual.Length ? -1 : shared;
    }
}
