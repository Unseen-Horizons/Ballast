namespace Ballast.Translations;

/// <summary>
/// The folders and files of one generation run: where the .resx files are, where the JSON files and the data script go, and the
/// options for the optional error-code map and the loader check. The defaults write the same files a site with
/// <c>SharedResources.resx</c> and <c>SharedResources.hr.resx</c> gets from the build script it replaces.
/// </summary>
public sealed class I18nGeneratorOptions
{
    /// <summary>
    /// The folder with the .resx files. Required. The files are read from this folder only, not from its subfolders.
    /// </summary>
    public string SourceDirectory { get; set; } = string.Empty;

    /// <summary>
    /// The base name of the files. The base file (<c>BaseName.resx</c>) is English. A culture file is <c>BaseName.culture.resx</c>, where the
    /// culture is letters, digits and underscores. The default is <c>SharedResources</c>.
    /// </summary>
    public string BaseName { get; set; } = "SharedResources";

    /// <summary>
    /// The folder the <c>culture.json</c> files are written to. Required. It is created when it is missing.
    /// </summary>
    public string OutputDirectory { get; set; } = string.Empty;

    /// <summary>
    /// The script file to write, such as <c>wwwroot/js/i18n-data.js</c>. Required. Its folder is created when it is missing.
    /// </summary>
    public string DataFile { get; set; } = string.Empty;

    /// <summary>
    /// A JSON object of error code to the key of its text, written into the script as <c>ERROR_CODE_MAP</c>. Null for none, which writes
    /// an empty map. When a path is given, the file must exist, and every value in it must be text.
    /// </summary>
    public string? ErrorCodesFile { get; set; }

    /// <summary>
    /// The web root whose HTML files are checked against <see cref="LoaderScript"/>. Null turns the check off. The folders named
    /// <c>i18n</c> are not searched.
    /// </summary>
    public string? WebRoot { get; set; }

    /// <summary>
    /// The loader script that the HTML files load, such as <c>/js/i18n.js</c>. Every HTML file that loads it must also load the
    /// data script (named by the <see cref="DataFile"/>'s file name) before it. Null turns the check off.
    /// </summary>
    public string? LoaderScript { get; set; }

    /// <summary>
    /// The first line of the script, without its line break. The default is <c>// Generated by Ballast.Translations — do not edit manually</c>.
    /// An app that must keep its previous header sets it here.
    /// </summary>
    public string Header { get; set; } = "// Generated by Ballast.Translations — do not edit manually";
}
